// npm run docs
// Generates the two documents whose content must match the database exactly:
//   docs/AUDIT_REPORT.md     (the 12 incidents, from audit.incidents + the evaluation)
//   docs/DATA_DICTIONARY.md  (every table and column, from information_schema)
import { writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { openDb, ROOT } from "./lib/db.ts";

const db = await openDb();
const q = async <T>(sql: string) => (await db.query<T>(sql)).rows;
const ev = JSON.parse(readFileSync(resolve(ROOT, "data/derived/evaluation.json"), "utf8"));
const pct = (v: number) => `${(v * 100).toFixed(1)}%`;

// ---------------------------------------------------------------- AUDIT_REPORT.md
type Inc = { incident_no: number; title: string; brand: string; start_date: Date; end_date: Date; kind: string; symptom: string; root_cause: string; evidence: string; impact: string; fix: string; status: string };
const inc = await q<Inc>(`SELECT * FROM audit.incidents ORDER BY incident_no`);
const d = (x: Date) => x.toISOString().slice(0, 10);
const st = (await q<{ status: string; n: number }>(`SELECT status, count(*)::int n FROM audit.lead_status GROUP BY 1 ORDER BY 2 DESC`));
const total = st.reduce((a, r) => a + r.n, 0);
let md = `# Audit report: twelve incidents, one false alarm

*SIMULATED data (fictional brands and platforms). Every number below is computed in SQL (\`db/transforms/80_incident_log.sql\`) and regenerated by \`npm run docs\`.*

## Summary

- **${total.toLocaleString("en-US")} CRM records audited**: ${st.map((r) => `${r.status} ${r.n.toLocaleString("en-US")} (${pct(r.n / total)})`).join(", ")}.
- **Detection quality** against the simulation's hidden answer key: ${ev.classes.map((c: { class: string; precision: number; recall: number }) => `${c.class} precision ${pct(c.precision)} / recall ${pct(c.recall)}`).join("; ")}.
- **Attribution**: right channel for ${pct(ev.attribution.corrected_accuracy)} of non-spam leads after correction, vs ${pct(ev.attribution.raw_accuracy)} from the CRM label alone.
- **One false alarm**: incident #11 is real demand (a heat wave), detected by the volume check and deliberately left uncorrected.

## How an incident was handled

1. A check fails or a number looks wrong (symptom).
2. Rule out tracking first: duplicates, spam, tags, time zones, mappings.
3. Find the root cause in the raw exports, measure the impact in SQL.
4. Fix at the source when possible, add a rule or a check so it cannot come back silently, and verify the fix with data.

| # | Incident | Brand | Period | Status |
|---|---|---|---|---|
${inc.map((i) => `| ${String(i.incident_no).padStart(2, "0")} | ${i.title} | ${i.brand} | ${d(i.start_date) === d(i.end_date) ? d(i.start_date) : `${d(i.start_date)} → ${d(i.end_date)}`} | ${i.kind === "false_signal" ? "Not a data issue" : i.status} |`).join("\n")}

`;
for (const i of inc) {
  md += `## #${String(i.incident_no).padStart(2, "0")} ${i.title}${i.kind === "false_signal" ? " (false alarm)" : ""}

- **Brand / period**: ${i.brand}, ${d(i.start_date)} → ${d(i.end_date)}
- **Symptom**: ${i.symptom}.
- **Root cause**: ${i.root_cause}.
- **Evidence**: ${i.evidence}.
- **Impact**: ${i.impact}.
- **Fix**: ${i.fix}.
- **Status**: ${i.status}.

`;
}
md += `## Known limits of the rules

- Spam missed by the rules (${ev.classes.find((c: { class: string }) => c.class === "spam").fn}) are mostly bots with a single weak signal (a real-looking US number, a clean inbox): below the 0.6 threshold on purpose, to protect real customers.
- Duplicates missed (${ev.classes.find((c: { class: string }) => c.class === "duplicate").fn}) are people who came back with another phone and another e-mail: no contact-based rule can link them.
- Precision and recall are measured against the simulation's answer key. In a real business, a reviewed random sample of flagged and unflagged leads replaces it.
`;
writeFileSync(resolve(ROOT, "docs/AUDIT_REPORT.md"), md);


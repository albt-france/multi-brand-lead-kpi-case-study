const cols = await q<{ s: string; t: string; c: string; ty: string; n: string }>(`
  SELECT table_schema s, table_name t, column_name c, data_type ty, is_nullable n FROM information_schema.columns
  WHERE table_schema IN ('raw', 'staging', 'core', 'audit', 'marts') ORDER BY
  array_position(ARRAY['raw','staging','core','audit','marts'], table_schema::text), table_name, ordinal_position`);
let dd = `# Data dictionary

Generated from the database (\`npm run docs\`). Schemas: **raw** (as exported, all text), **staging** (normalized), **core** (business model), **audit** (rules, verdicts, checks, history), **marts** (views read by the dashboard and Looker Studio).

`;
let cur = "";
for (const r of cols) {
  const k = `${r.s}.${r.t}`;
  if (k !== cur) { dd += `\n## ${k}\n\n${DESC[k] ?? ""}\n\n| Column | Type | Nullable |\n|---|---|---|\n`; cur = k; }
  dd += `| ${r.c} | ${r.ty} | ${r.n === "YES" ? "yes" : "no"} |\n`;
}
writeFileSync(resolve(ROOT, "docs/DATA_DICTIONARY.md"), dd);
console.log(`docs written: AUDIT_REPORT.md (${inc.length} incidents), DATA_DICTIONARY.md (${new Set(cols.map((c) => c.s + c.t)).size} tables/views)`);
await db.close();
